/// `git rev-parse --show-toplevel` from `dir`; `None` when not a git repo.
fn detect_git_root(dir: &Path) -> Option<PathBuf> {
    let out = std::process::Command::new("git")
        .arg("-C")
        .arg(dir)
        .args(["rev-parse", "--show-toplevel"])
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    let root = String::from_utf8_lossy(&out.stdout).trim().to_string();
    if root.is_empty() {
        None
    } else {
        Some(PathBuf::from(root))
    }
}

/// Project name from the origin remote URL, falling back to the directory
/// name (rvl-cli `project.DetectProjectName`).
fn detect_project_name(git_root: &Path) -> String {
    if let Ok(out) = std::process::Command::new("git")
        .arg("-C")
        .arg(git_root)
        .args(["remote", "get-url", "origin"])
        .output()
    {
        if out.status.success() {
            let remote = String::from_utf8_lossy(&out.stdout).trim().to_string();
            let remote = remote
                .strip_suffix(".git")
                .map(str::to_string)
                .unwrap_or(remote);
            if let Some(seg) = remote.rsplit('/').next() {
                let name = seg.rsplit(':').next().unwrap_or(seg);
                if !name.is_empty() {
                    return name.to_string();
                }
            }
        }
    }
    git_root
        .file_name()
        .map(|n| n.to_string_lossy().to_string())
        .unwrap_or_else(|| "project".to_string())
}


//! `init` ported from rvl-cli `internal/commands/init.go` (po-av01j.163):
//! initialize Revelara for a repository.
//!
//! What it does, in rvl-cli's order: require a git repo, write
//! `.revelara.yaml` (project name + detected components) in the EXACT byte
//! shape rvl-cli's yaml.v3 marshal produces (4-space-indented list items
//! under `components:`), seed `.revelara/memory/digest.compact`, optionally
//! install the plugin skills, check credentials, fire the onboarding
//! milestone, and print the summary.
//!
//! Steps 4 and 5 write the REVELARA MANAGED BLOCK into `AGENTS.md` and
//! `CLAUDE.md` (see [`crate::context_files`]). init OWNS those files during
//! onboarding: it prompts about them itself, which is why the plugin step it
//! delegates to must not write them a second time.
//!
//! Deliberate deviations from the Go source:
//! * The plugin step DELEGATES to the rvl skills machinery (the same
//!   engine as `plugin install`) via a caller-supplied closure instead of
//!   porting rvl-cli's `internal/plugin` installer.
//! * `--no-context-files` is accepted here as well as on `plugin
//!   install`/`update`; rvl-cli carries it on the plugin commands only.
//! * Interactive prompts are plain stdin lines (matching `login`), not huh
//!   TUI forms. Only non-interactive paths (`-y`, flags) are tested.
//! * `--force` overwrites an existing `.revelara.yaml` without prompting,
//!   which is what rvl-cli's help text promises ("Overwrite existing config
//!   and plugin without prompting") even though its code still prompted.

use crate::context_files::Action;
use rvl_data::BIN;
use std::collections::HashSet;
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

/// Flags for `init`, mirroring rvl-cli's
/// `--project/--skip-plugin/--force/-y`.
pub struct InitArgs {
    pub project: Option<String>,
    pub skip_plugin: bool,
    pub force: bool,
    pub yes: bool,
    /// Skip steps 4 and 5 (the AGENTS.md/CLAUDE.md managed blocks).
    pub no_context_files: bool,
}

/// One `components:` entry in `.revelara.yaml` (rvl-cli
/// `project.ProjectComponent`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Component {
    pub name: String,
    pub path: String,
}

/// The comment header rvl-cli's `project.WriteProjectConfig` prepends.
const CONFIG_HEADER: &str = "# Revelara project configuration\n\
     # Used by /rvl:scan and reliability-review skills for consistent service naming\n";

/// The `.revelara/memory/digest.compact` skeleton (po-ta8wj.1 in rvl-cli).
const DIGEST_SKELETON: &str = "# digest.compact v1 - auto-generated by rvl init\n\
     # Do not hand-edit. Human-readable history is in RISKS.md and ENTRYPOINT.md.\n";

/// `init`: the full rvl-cli flow. `install_plugin` runs the rvl skills
/// machinery and reports whether any harness ended up installed.
pub fn run(args: InitArgs, install_plugin: impl FnOnce() -> anyhow::Result<bool>) -> ExitCode {
    println!("Initializing Revelara...");
    println!();

    // Step 1: require a git repo.
    let Some(git_root) = detect_git_root(Path::new(".")) else {
        eprintln!("Error: not a git repository.");
        eprintln!(
            "Revelara reads your git repository to detect project structure and service names."
        );
        eprintln!("Navigate to a git repository or run 'git init' here first.");
        return ExitCode::FAILURE;
    };

    // Step 2: generate .revelara.yaml.
    let config_path = git_root.join(".revelara.yaml");
    let mut write_config = true;
    if config_path.exists() {
        if args.force {
            // Documented --force contract: overwrite without prompting.
        } else if args.yes {
            write_config = false;
            println!("Keeping existing .revelara.yaml (use interactive mode to overwrite)");
        } else {
            let existing = std::fs::read_to_string(&config_path).unwrap_or_default();
            println!("Existing .revelara.yaml found:");
            println!("{existing}");
            if !crate::confirm("Overwrite existing .revelara.yaml?") {
                write_config = false;
                println!("Keeping existing .revelara.yaml");
            }
        }
    }

    let (project, components) = if write_config {
        let (project, declared, candidates) = build_project_config(&git_root, args.project, args.yes);
        if let Err(e) = std::fs::write(
            &config_path,
            render_config_yaml(&project, &declared, &candidates),
        ) {
            eprintln!("Error writing .revelara.yaml: {e}");
            return ExitCode::FAILURE;
        }
        match (declared.len(), candidates.len()) {
            (0, 0) => println!("Created .revelara.yaml (project: {project}, no components)"),
            (d, 0) => println!("Created .revelara.yaml (project: {project}, {d} declared components)"),
            (0, c) => println!(
                "Created .revelara.yaml (project: {project}, {c} candidate components commented out - uncomment to declare)"
            ),
            (d, c) => println!(
                "Created .revelara.yaml (project: {project}, {d} declared components, {c} candidates commented out)"
            ),
        }
        (project, declared)
    } else {
        load_existing(&config_path)
    };

    // Seed .revelara/memory/digest.compact if absent (best-effort).
    let memory_dir = git_root.join(".revelara").join("memory");
    match std::fs::create_dir_all(&memory_dir) {
        Err(e) => eprintln!("Warning: could not create .revelara/memory/: {e}"),
        Ok(()) => {
            let digest = memory_dir.join("digest.compact");
            if !digest.exists() {
                if let Err(e) = std::fs::write(&digest, DIGEST_SKELETON) {
                    eprintln!("Warning: could not write digest.compact: {e}");
                }
            }
        }
    }
    println!();

    // Step 3: install skills (the plugin) unless skipped.
    let mut plugin_installed = false;
    if !args.skip_plugin {
        let do_install = args.yes
            || args.force
            || crate::confirm("Install the Revelara plugin skills for detected coding agents?");
        if do_install {
            match install_plugin() {
                Ok(installed) => plugin_installed = installed,
                Err(e) => eprintln!("Warning: could not install skills: {e}"),
            }
        }
        println!();
    }

    // Step 4: the AGENTS.md managed block. Written for every repo, plugin
    // or not: it is how a harness with no slash commands finds rvl at all.
    let agents_md_action = if args.no_context_files {
        None
    } else {
        ensure_agents_md_interactive(&git_root, args.force, args.yes)
    };

    // Step 5: the CLAUDE.md managed block, only once skills are installed
    // (rvl-cli gates this on `pluginInstalled` — with no agent on the
    // machine there is nothing to give the extra Claude-only routing to).
    let claude_md_action = if args.no_context_files || !plugin_installed {
        None
    } else {
        report_context_action(
            "CLAUDE.md",
            crate::context_files::ensure_claude_md(&git_root, args.yes || args.force),
        )
    };
    if agents_md_action.is_some() || claude_md_action.is_some() {
        println!();
    }

    // Step 6: check credentials; on success record the onboarding
    // milestone (fire-and-forget, mirroring rvl-cli's "cli_setup").
    let mut credentials_configured = false;
    if let Ok(Some(cfg)) = rvl_data::config::load() {
        credentials_configured = true;
        println!("Credentials: Configured (API URL: {})", cfg.api_url);
        post_onboarding_milestone(&cfg);
    } else {
        println!("Credentials: Not configured");
        println!("  Run '{BIN} login' to set up API credentials.");
    }
    println!();

    // Step 7: summary.
    print_summary(
        &project,
        &components,
        plugin_installed,
        credentials_configured,
        agents_md_action,
        claude_md_action,
    );
    ExitCode::SUCCESS
}

/// rvl-cli `commands.EnsureAgentsMd`: prompt before touching an EXISTING
/// AGENTS.md (creating a fresh one was never prompted for), then delegate the
/// write so init and `plugin install` share one implementation.
fn ensure_agents_md_interactive(git_root: &Path, force: bool, yes: bool) -> Option<Action> {
    use crate::context_files::State;
    let mut proceed = force || yes;
    if !proceed {
        let title = match crate::context_files::agents_md_state(git_root) {
            State::Missing => {
                proceed = true;
                None
            }
            State::Unmanaged => Some("AGENTS.md exists but has no Revelara section. Append?"),
            State::Managed => Some("AGENTS.md already has Revelara section. Update?"),
        };
        if let Some(title) = title {
            if !crate::confirm(title) {
                println!("AGENTS.md: Skipped");
                return None;
            }
            proceed = true;
        }
    }
    if !proceed {
        println!("AGENTS.md: Skipped");
        return None;
    }
    report_context_action(
        "AGENTS.md",
        crate::context_files::ensure_agents_md(git_root, true),
    )
}

/// Print rvl-cli's per-action line and return the action when it wrote
/// something. A failure is a WARNING: init has already produced the config
/// the user asked for, and a context file is not worth failing over.
fn report_context_action(name: &str, res: anyhow::Result<Action>) -> Option<Action> {
    match res {
        Err(e) => {
            eprintln!("Warning: could not set up {name}: {e}");
            None
        }
        Ok(Action::Skipped) => {
            println!("{name}: Skipped");
            None
        }
        Ok(action) => {
            let verb = match action {
                Action::Created => "Created",
                Action::Appended => "Appended Revelara managed block to",
                Action::Updated => "Updated Revelara managed block in",
                Action::Skipped => unreachable!(),
            };
            match action {
                Action::Created => println!("Created {name} with Revelara managed block"),
                _ => println!("{verb} {name}"),
            }
            Some(action)
        }
    }
}

/// Fire-and-forget onboarding milestone. Errors are silently discarded so
/// init is never blocked or failed on behalf of a telemetry-style call
/// (rvl-cli `api.PostOnboardingMilestone`).
fn post_onboarding_milestone(cfg: &rvl_data::config::DataConfig) {
    if cfg.api_key.is_empty() || cfg.api_url.is_empty() {
        return;
    }
    let client = rvl_data::client::Client {
        api_url: cfg.api_url.clone(),
        api_key: cfg.api_key.clone(),
        org_id: None,
    };
    let url = format!("{}/api/v1/onboarding/milestone", cfg.api_url);
    let _ = client.request_with_timeout(
        "POST",
        &url,
        Some(br#"{"milestone":"cli_setup"}"#),
        std::time::Duration::from_secs(5),
    );
}

/// Port of rvl-cli's `printInitSummary`, minus the skills version (the
/// install machinery prints per-harness versions as it runs).
fn print_summary(
    project: &str,
    components: &[Component],
    plugin_installed: bool,
    credentials_configured: bool,
    agents_md_action: Option<Action>,
    claude_md_action: Option<Action>,
) {
    println!("=== Revelara Initialization Complete ===");
    println!();
    println!("Project: {project}");
    println!("Components: {}", components.len());
    for c in components {
        println!("  - {} ({})", c.name, c.path);
    }
    println!();
    if plugin_installed {
        println!("Skills: Installed");
    } else {
        println!("Skills: Not installed");
    }
    if let Some(a) = agents_md_action {
        println!("AGENTS.md: {}", a.as_str());
    }
    if let Some(a) = claude_md_action {
        println!("CLAUDE.md: {}", a.as_str());
    }
    if credentials_configured {
        println!("Credentials: Configured");
    } else {
        println!("Credentials: Not configured - run '{BIN} login'");
    }
    println!();
    println!("Next steps:");
    if !credentials_configured {
        println!("  1. {BIN} login");
        println!("  2. {BIN} plugin install claude");
    } else if !plugin_installed {
        println!("  1. {BIN} plugin install claude");
    }
    match (agents_md_action.is_some(), claude_md_action.is_some()) {
        (true, true) => {
            println!("  - Commit .revelara.yaml, AGENTS.md, and CLAUDE.md to your repository")
        }
        (true, false) => println!("  - Commit .revelara.yaml and AGENTS.md to your repository"),
        _ => println!("  - Commit .revelara.yaml to your repository"),
    }
    println!(
        "  - Open Claude Code in this directory and run /rvl:scan to scan for reliability risks"
    );
}


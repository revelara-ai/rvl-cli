/// Dedup-by-path collector preserving insertion order, mirroring rvl-cli's
/// `addComponent` closure.
struct Collector {
    components: Vec<Component>,
    seen: HashSet<String>,
}

impl Collector {
    fn add(&mut self, name: impl Into<String>, path: impl Into<String>) {
        let path = path.into();
        if self.seen.insert(path.clone()) {
            self.components.push(Component {
                name: name.into(),
                path,
            });
        }
    }
}

fn base_name(path: &str) -> &str {
    path.trim_end_matches('/')
        .rsplit('/')
        .next()
        .unwrap_or(path)
}

fn excluded(name: &str) -> bool {
    EXCLUDE_DIRS.contains(&name)
}

/// Sorted directory entries (Go's `os.ReadDir` returns sorted entries;
/// Rust's `read_dir` does not, so sort for the same deterministic output).
fn sorted_dir(path: &Path) -> Vec<std::fs::DirEntry> {
    let mut entries: Vec<_> = match std::fs::read_dir(path) {
        Ok(rd) => rd.flatten().collect(),
        Err(_) => Vec::new(),
    };
    entries.sort_by_key(std::fs::DirEntry::file_name);
    entries
}

fn is_dir_entry(entry: &std::fs::DirEntry) -> bool {
    entry.file_type().map(|t| t.is_dir()).unwrap_or(false)
}

/// Multi-phase component detection, a faithful port of rvl-cli
/// `project.DetectComponents`: workspace declarations, build-file scanning
/// under common layout dirs, `cmd/*/main.go`, root Flutter apps, and
/// directories with Dockerfiles.
/// po-7p45k.23: a workspace member is a service CANDIDATE only when it is
/// separately runnable. A library crate/module is internal structure; its
/// findings belong to the project service, and proposing it would mint an
/// org-unique service for something that never deploys.
fn rust_member_has_binary(member: &Path) -> bool {
    if member.join("src/main.rs").exists() {
        return true;
    }
    if let Ok(entries) = std::fs::read_dir(member.join("src/bin")) {
        for e in entries.flatten() {
            if e.path().extension().is_some_and(|x| x == "rs") {
                return true;
            }
        }
    }
    std::fs::read_to_string(member.join("Cargo.toml"))
        .map(|t| t.contains("[[bin]]"))
        .unwrap_or(false)
}

/// Same gate for go.work members: `main.go` at the member root or a `cmd/`
/// tree marks a runnable module; anything else is a shared library.
fn go_member_has_binary(member: &Path) -> bool {
    member.join("main.go").exists() || member.join("cmd").is_dir()
}

pub(crate) fn detect_components(root: &Path) -> Vec<Component> {
    let mut col = Collector {
        components: Vec::new(),
        seen: HashSet::new(),
    };

    // Phase 1: workspace declarations.

    // Go workspaces (go.work).
    if let Ok(data) = std::fs::read_to_string(root.join("go.work")) {
        for line in data.lines() {
            let line = line.trim();
            if line.starts_with("use ") || (line.starts_with("./") && !line.starts_with("//")) {
                let dir = line.strip_prefix("use ").unwrap_or(line).trim();
                let dir = dir.trim_matches(|c| c == '.' || c == '/');
                if !dir.is_empty() && dir != "." && go_member_has_binary(&root.join(dir)) {
                    col.add(base_name(dir), format!("{dir}/"));
                }
            }
        }
    }

    // Rust workspaces (Cargo.toml [workspace] members). Same line-oriented
    // extraction as the Go source, including its quirk of skipping lines
    // that start with "members" (single-line member arrays go undetected).
    if let Ok(content) = std::fs::read_to_string(root.join("Cargo.toml")) {
        if content.contains("[workspace]") {
            for line in content.lines() {
                let line = line.trim();
                if line.contains('"') && !line.starts_with('#') && !line.starts_with("members") {
                    for part in line.split('"') {
                        let part = part.trim();
                        if !part.is_empty()
                            && !part.chars().any(|c| "[]=#,".contains(c))
                            && root.join(part).exists()
                            && rust_member_has_binary(&root.join(part))
                        {
                            col.add(base_name(part), format!("{part}/"));
                        }
                    }
                }
            }
        }
    }

    // JS/TS workspaces (package.json "workspaces").
    if let Ok(data) = std::fs::read_to_string(root.join("package.json")) {
        if let Ok(pkg) = serde_json::from_str::<serde_json::Value>(&data) {
            let mut patterns: Vec<String> = Vec::new();
            match pkg.get("workspaces") {
                Some(serde_json::Value::Array(arr)) => {
                    patterns.extend(arr.iter().filter_map(|v| v.as_str().map(String::from)));
                }
                Some(serde_json::Value::Object(obj)) => {
                    // Yarn v1 style: { "packages": ["..."] }.
                    if let Some(serde_json::Value::Array(arr)) = obj.get("packages") {
                        patterns.extend(arr.iter().filter_map(|v| v.as_str().map(String::from)));
                    }
                }
                _ => {}
            }
            for pattern in patterns {
                for m in glob_paths(root, &pattern) {
                    if m.is_dir() {
                        if let Ok(rel) = m.strip_prefix(root) {
                            let rel = rel.to_string_lossy().to_string();
                            if !rel.is_empty() && rel != "." {
                                col.add(base_name(&rel), format!("{rel}/"));
                            }
                        }
                    }
                }
            }
        }
    }

    // Java Maven modules (pom.xml <modules>).
    if let Ok(content) = std::fs::read_to_string(root.join("pom.xml")) {
        let mut rest = content.as_str();
        while let Some(start) = rest.find("<module>") {
            rest = &rest[start + 8..];
            let Some(end) = rest.find("</module>") else {
                break;
            };
            let module = rest[..end].trim().to_string();
            rest = &rest[end + 9..];
            if !module.is_empty() && root.join(&module).exists() {
                col.add(base_name(&module), format!("{module}/"));
            }
        }
    }

    // Gradle subprojects (settings.gradle / settings.gradle.kts).
    for settings in ["settings.gradle", "settings.gradle.kts"] {
        if let Ok(data) = std::fs::read_to_string(root.join(settings)) {
            for line in data.lines() {
                let line = line.trim();
                if line.contains("include") {
                    for part in line.split('\'') {
                        let part = part.trim();
                        let part = part.strip_prefix(':').unwrap_or(part);
                        if !part.is_empty() && !part.chars().any(|c| "()=,".contains(c)) {
                            let dir = part.replace(':', "/");
                            if root.join(&dir).exists() {
                                col.add(base_name(&dir).to_string(), format!("{dir}/"));
                            }
                        }
                    }
                }
            }
        }
    }

    // C# solution files (*.sln).
    for sln in glob_paths(root, "*.sln") {
        if let Ok(data) = std::fs::read_to_string(&sln) {
            for line in data.lines() {
                if line.contains("Project(") && line.contains(".csproj") {
                    for part in line.split('"') {
                        if part.ends_with(".csproj") || part.ends_with(".fsproj") {
                            let dir = match part.rfind('/') {
                                Some(i) => &part[..i],
                                None => ".",
                            };
                            if !dir.is_empty() && dir != "." {
                                let dir = dir.replace('\\', "/");
                                if root.join(&dir).exists() {
                                    col.add(base_name(&dir).to_string(), format!("{dir}/"));
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    // Dart/Flutter Melos workspaces (melos.yaml).
    if let Ok(data) = std::fs::read_to_string(root.join("melos.yaml")) {
        let mut in_packages = false;
        for line in data.lines() {
            let trimmed = line.trim();
            if trimmed == "packages:" {
                in_packages = true;
                continue;
            }
            if in_packages {
                if !trimmed.starts_with('-') && !trimmed.is_empty() {
                    break; // end of packages list
                }
                if let Some(pattern) = trimmed.strip_prefix("- ") {
                    for m in glob_paths(root, pattern.trim()) {
                        if m.is_dir() && m.join("pubspec.yaml").exists() {
                            if let Ok(rel) = m.strip_prefix(root) {
                                let rel = rel.to_string_lossy().to_string();
                                col.add(base_name(&rel).to_string(), format!("{rel}/"));
                            }
                        }
                    }
                }
            }
        }
    }

    // Phase 2: build files under common layout directories.
    for dir in [
        "services", "cmd", "apps", "packages", "libs", "modules", "internal",
    ] {
        for entry in sorted_dir(&root.join(dir)) {
            let name = entry.file_name().to_string_lossy().to_string();
            if !is_dir_entry(&entry) || excluded(&name) {
                continue;
            }
            let sub = format!("{dir}/{name}");
            if BUILD_FILES
                .iter()
                .any(|bf| root.join(&sub).join(bf).exists())
            {
                col.add(name, format!("{sub}/"));
            }
        }
    }

    // Phase 3: Go cmd/ pattern (directories with main.go).
    for entry in sorted_dir(&root.join("cmd")) {
        if !is_dir_entry(&entry) {
            continue;
        }
        let name = entry.file_name().to_string_lossy().to_string();
        if root.join("cmd").join(&name).join("main.go").exists() {
            col.add(name.clone(), format!("cmd/{name}/"));
        }
    }

    // Phase 3b: root Flutter/Dart app (pubspec.yaml + lib/).
    if root.join("pubspec.yaml").exists() && root.join("lib").exists() {
        if let Ok(data) = std::fs::read_to_string(root.join("pubspec.yaml")) {
            for line in data.lines() {
                if let Some(name) = line.trim().strip_prefix("name:") {
                    let name = name.trim();
                    if !name.is_empty() {
                        col.add(name.to_string(), ".");
                    }
                    break;
                }
            }
        }
    }

    // Phase 4: directories with Dockerfiles.
    for entry in sorted_dir(root) {
        let name = entry.file_name().to_string_lossy().to_string();
        if !is_dir_entry(&entry) || excluded(&name) {
            continue;
        }
        if root.join(&name).join("Dockerfile").exists() {
            col.add(name.clone(), format!("{name}/"));
        }
    }

    col.components
}

// --- minimal glob (Go filepath.Glob subset: `*` within a path segment) ---

/// Expand a glob pattern relative to `root`. Supports `*` within single
/// path segments (the shape of workspace globs like `packages/*`), which is
/// the subset rvl-cli's `filepath.Glob` calls rely on. Results are sorted.
fn glob_paths(root: &Path, pattern: &str) -> Vec<PathBuf> {
    let mut cur = vec![root.to_path_buf()];
    for seg in pattern.split('/').filter(|s| !s.is_empty()) {
        let mut next = Vec::new();
        if seg.contains('*') {
            for base in &cur {
                for entry in sorted_dir(base) {
                    let name = entry.file_name().to_string_lossy().to_string();
                    if seg_match(seg, &name) {
                        next.push(base.join(name));
                    }
                }
            }
        } else {
            for base in &cur {
                let p = base.join(seg);
                if p.exists() {
                    next.push(p);
                }
            }
        }
        cur = next;
    }
    cur.sort();
    cur
}

/// Match one glob segment (`*` = any run of characters) against a name.
fn seg_match(pattern: &str, name: &str) -> bool {
    let parts: Vec<&str> = pattern.split('*').collect();
    if parts.len() == 1 {
        return pattern == name;
    }
    let (first, last) = (parts[0], parts[parts.len() - 1]);
    if !name.starts_with(first) || !name.ends_with(last) {
        return false;
    }
    if name.len() < first.len() + last.len() {
        return false;
    }
    let mut rest = &name[first.len()..name.len() - last.len()];
    for part in &parts[1..parts.len() - 1] {
        if part.is_empty() {
            continue;
        }
        match rest.find(part) {
            Some(idx) => rest = &rest[idx + part.len()..],
            None => return false,
        }
    }
    true
}

